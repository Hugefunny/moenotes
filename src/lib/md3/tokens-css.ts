/**
 * The stylesheet of the default Material 3 color schemes (src/styles/md3/colors.css), generated from
 * MD3_DEFAULT_SEED by scripts/generate-md3-tokens.ts. A test keeps the committed file equal to this output.
 */
import { colorDeclarations, type Md3Colors } from "@/lib/md3/roles";
import { MD3_DEFAULT_SEED, md3Schemes } from "@/lib/md3/scheme";

function block(selector: string, colors: Md3Colors, colorScheme: "light" | "dark"): string {
  const lines = [`  color-scheme: ${colorScheme};`, ...colorDeclarations(colors).map(([name, value]) => `  ${name}: ${value};`)];
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

export function buildMd3ColorsCss(seed: string = MD3_DEFAULT_SEED): string {
  const schemes = md3Schemes(seed);
  if (!schemes) throw new Error(`Not a #RRGGBB seed: ${seed}`);
  return [
    "/* Generated by scripts/generate-md3-tokens.ts from the default seed " + seed + " (neutral surfaces, seed accents). Do not edit:\n",
    "   run `bun scripts/generate-md3-tokens.ts`. A band color chosen in the settings overrides these variables on\n",
    "   <html> at runtime (src/lib/settings/apply-theme.ts). */\n",
    block(":root", schemes.light, "light"),
    "\n",
    block('html[data-theme="dark"]', schemes.dark, "dark"),
  ].join("");
}
