/**
 * Writes server/internal/siteconfig/site.json: the facts about the site that the Go deploy server needs and that the
 * TypeScript sources own (locales and their path prefixes, player page rules, the default public data endpoints).
 * The Go server embeds the file, so a locale or game server added in src/config reaches it without a hand-written copy.
 *
 *   bun scripts/generate-runtime-config.ts          write the file
 *   bun scripts/generate-runtime-config.ts --check  fail when the committed file is out of date (lint, CI)
 *
 * Run with Bun: the config modules read `import.meta.env`, which Bun provides.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const target = fileURLToPath(new URL("../server/internal/siteconfig/site.json", import.meta.url));

// Defaults only: PUBLIC_* overrides of the deploy environment are applied by the Go server at runtime.
for (const name of Object.keys(process.env)) {
  if (name.startsWith("PUBLIC_")) delete process.env[name];
}
const { LOCALE_PATH_PREFIX, SUPPORTED_LOCALES } = await import("../src/config/locales");
const { GAME_PROFILE_ID_PATTERNS, GAME_SERVERS, PLAYER_PAGE_PATH } = await import("../src/config/players");
const { assetConfig } = await import("../src/config/assets");
const { masterdataConfig } = await import("../src/config/masterdata");

const config = {
  $comment: "Generated by scripts/generate-runtime-config.ts from src/config. Do not edit by hand.",
  locales: SUPPORTED_LOCALES.map((code) => ({ code, prefix: LOCALE_PATH_PREFIX[code] })),
  player: {
    path: PLAYER_PAGE_PATH,
    servers: GAME_SERVERS.map((server) => ({ server, profileId: GAME_PROFILE_ID_PATTERNS[server].source })),
    /** JP profile IDs are signed int64: 19-digit IDs are compared with this as decimal text. */
    maxJpProfileId: "9223372036854775807",
  },
  upstream: {
    assetApi: assetConfig.api,
    assetVersionPath: "/versions/current_version.json",
    masterdata: Object.values(masterdataConfig.sources)[0],
    masterdataVersionPath: masterdataConfig.versionPath,
  },
};
const expected = `${JSON.stringify(config, null, 2)}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // Missing counts as out of date.
  }
  if (current !== expected) {
    console.error(`[moenotes] ${target} is out of date; run: bun scripts/generate-runtime-config.ts`);
    process.exit(1);
  }
  console.log("[moenotes] server runtime config is up to date");
} else {
  writeFileSync(target, expected);
  console.log(`[moenotes] wrote ${target}`);
}
